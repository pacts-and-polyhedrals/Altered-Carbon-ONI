import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'module.json'),'utf8'));
const check=(condition,reason)=>{if(!condition)throw new Error(reason);};
check(manifest.id==='altered-carbon-oni','Unexpected module ID.');check(manifest.compatibility.minimum==='14','Foundry v14 minimum missing.');
check(manifest.relationships.systems[0].compatibility.minimum==='2.4.9','System minimum missing.');
check(manifest.socket===false,'ONI must not broadcast private content over a module socket.');
for(const file of [...manifest.esmodules,...manifest.styles,'templates/interface.hbs'])check(fs.existsSync(path.join(root,file)),`Missing runtime file: ${file}`);
const modules=fs.readdirSync(path.join(root,'scripts')).filter(f=>f.endsWith('.mjs'));
for(const name of modules)execFileSync(process.execPath,['--check',path.join(root,'scripts',name)]);
const source=modules.filter(n=>n!=='validate.mjs').map(n=>fs.readFileSync(path.join(root,'scripts',n),'utf8')).join('\n');
check(!/game\.socket|socket\.emit/.test(source),'Unsealed socket transport found.');
check(fs.readFileSync(path.join(root,'templates/interface.hbs'),'utf8').includes('{{{body}}}'),'Interface template invalid.');
check(!source.includes('eval('),'Unexpected executable payload evaluation.');
const pkg=path.join(root,'package.json');if(fs.existsSync(pkg))check(JSON.parse(fs.readFileSync(pkg,'utf8')).version===manifest.version,'Version mismatch.');
console.log(JSON.stringify({ok:true,version:manifest.version,syntaxModules:modules.length,foundryMinimum:14,systemMinimum:'2.4.9',transport:'signed encrypted ChatMessages'}));
